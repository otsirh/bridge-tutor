/** ♣ ♦ ♥ ♠ oder SA */
const sym = (s: number) => (s === 4 ? core.nt : SUIT_SYMBOLS[s]);
const syms = (list: number[], sep: string) => list.map(sym).join(sep);
/** „♠, ♥ und ♦“ */
const symList = (list: number[]) => {
  const xs = list.map(sym);
  return xs.length > 1 ? `${xs.slice(0, -1).join(', ')} und ${xs[xs.length - 1]}` : (xs[0] ?? '');
};
/** „12–14“, or „18“ when both ends are the same. */
