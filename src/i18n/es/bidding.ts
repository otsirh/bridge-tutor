// Bidding system: rule names, explanations, conditions.
//
// Same layout as src/i18n/en/bidding.ts (see the notes there). Suits arrive as
// indexes; Spanish names a suit by its plural ("un buen palo de corazones",
// "apoyo de tres cartas en picas"). "Picas" is feminine and the other suits
// masculine, so a suit with an article goes through `the`.
// "PH" (puntos de honor) is high-card points; "puntos" also count length or shortness.

