/** ♣ ♦ ♥ ♠, or SA */
const sym = (s: number) => (s === 4 ? core.nt : SUIT_SYMBOLS[s]);
const syms = (list: number[], sep: string) => list.map(sym).join(sep);
/** Plural: "cinco o más corazones". */
const plural = (s: number) => core.suits[s];
/** With the article: "los corazones", "las picas". */
const the = (s: number) => `${s === 3 ? 'las' : 'los'} ${core.suits[s]}`;
/** "1 perdedora", "3 perdedoras". */
const count = (n: number, one: string, many: string) => `${n} ${n === 1 ? one : many}`;

