/** ♣ ♦ ♥ ♠ или БК */
const sym = (s: number) => (s === 4 ? core.nt : SUIT_SYMBOLS[s]);
const syms = (list: number[], sep: string) => list.map(sym).join(sep);
/** "♥", "♥ и ♠", "♥, ♦ и ♠" */
const andList = (list: number[]) => (list.length > 1 ? `${syms(list.slice(0, -1), ', ')} и ${sym(list[list.length - 1])}` : syms(list, ''));
/** "13+ очков", "22+ очка" */
const ptsPlus = (n: number) => `${n}+ ${pl(n, 'очко', 'очка', 'очков')}`;
/** "15–17 очков", "20–21 очко" */
const ptsRange = (lo: number, hi: number) => `${lo}–${hi} ${pl(hi, 'очко', 'очка', 'очков')}`;
const totalWord = (n: number) => pl(n, 'общее очко', 'общих очка', 'общих очков');
/** "4+ червы", "5+ червей" */
const suitPlus = (n: number, s: number) => `${n}+ ${pl(n, SUIT_ONE[s], SUIT_NOM[s], SUIT_GEN[s])}`;
const cards = (n: number) => pl(n, 'карта', 'карты', 'карт');

