// Bidding system: rule names, explanations, conditions.
//
// Suits arrive as indexes (0 = clubs … 3 = spades; 4 = notrump where a strain
// is meant). Each template picks the case it needs from ./grammar: "pięć
// kierów" (genitive), "cztery kiery" (nominative), "w kierach" (locative),
// "kolor kierowy" (adjective). "PC" are high-card points; "punkty" also count
// length or shortness.

import type { Text } from '../en';
import { SUIT_SYMBOLS } from '../../core/cards';
import { core } from './core';
import { SUIT, adj, count } from './grammar';

/** ♣ ♦ ♥ ♠ or BA */
const sym = (s: number) => (s === 4 ? core.nt : SUIT_SYMBOLS[s]);
const syms = (list: number[], sep: string) => list.map(sym).join(sep);
/** Genitive plural: "pięć kierów", "5+ kierów". */
const gen = (s: number) => SUIT.gen[s];
/** Nominative plural: "cztery kiery", "licytuj kiery". */
const nom = (s: number) => SUIT.nom[s];
/** Locative plural: "w kierach", "o kierach". */
const loc = (s: number) => SUIT.loc[s];
/** Instrumental plural: "z pięcioma kierami". */
const ins = (s: number) => SUIT.ins[s];
const pts = (n: number) => count(n, 'punkt', 'punkty', 'punktów');
/** Length as the first part of an adjective: "ośmio|kartowy". */
