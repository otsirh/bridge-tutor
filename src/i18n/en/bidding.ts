// Bidding system: rule names, explanations, conditions.
//
// `names` holds the short label of every rule. Its key is the rule's identity
// in the engine: rules with the same key are variants of one bid and are read
// together, so each key gets exactly one label (some take the call's level or
// suit). The other sections follow the auction: openings, responses, rebids,
// competitive bidding, slam conventions, general judgment, natural calls, and
// the condition texts shared by all of them.
//
// Suits arrive as indexes (0 = clubs, 1 = diamonds, 2 = hearts, 3 = spades;
// 4 = notrump where a strain is meant), so each language picks its own words.
// "HCP" is high-card points; "points" also count length or shortness.

import { SUIT_SYMBOLS } from '../../core/cards';
